#!/usr/bin/env python3
"""Build data/chain-menus.js from the transcribed official nutrition tables in tools/chain-data/.

Every row is checked: 4 kcal/g protein and carbohydrate, 9 kcal/g fat must land within 15 % (or 15 kcal) of the printed
energy. A row that fails is left out and listed, never "fixed" silently. Run: python3 tools/build_chain_menus.py
"""
import json, pathlib, re, sys, unicodedata

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'tools' / 'chain-data'
CHAINS = [
    {'name': 'KFC', 'short': ['kfc'], 'file': 'kfc.txt', 'kind': 'kfc',
     'ref': 'KFC Magyarország tápérték táblázat (AmRest), kfc_hun_tapertek_wolt.pdf (2026. októberi változat)',
     'refEn': 'KFC Hungary nutrition table (AmRest), kfc_hun_tapertek_wolt.pdf (October 2026 version)'},
    {'name': 'Pizza Hut', 'short': ['pizza hut', 'pizzahut'], 'file': 'pizzahut.txt', 'kind': 'simple',
     'ref': 'Pizza Hut Magyarország tápérték táblázat (AmRest), 2024.02.13.',
     'refEn': 'Pizza Hut Hungary nutrition table (AmRest), 13 Feb 2024'},
    {'name': 'Starbucks', 'short': ['starbucks', 'sbux'], 'file': 'starbucks-food.txt', 'kind': 'simple',
     'ref': 'Starbucks Magyarország ételkínálat tápérték információ, starbucks.hu (2026.02.27.)',
     'refEn': 'Starbucks Hungary food nutrition information, starbucks.hu (27 Feb 2026)'},
]
CRUST_ALIASES = {
    'pan': ['{n}', '{n} pizza', '{n} pan', '{n} pan pizza'],
    'sf': ['{n} san francisco', '{n} sf', '{n} san francisco pizza'],
    'stuffed': ['{n} sajtos szelu', '{n} sajttal toltott szellel', '{n} toltott szelu', '{n} stuffed crust'],
}


def num(s):
    s = s.strip().replace(',', '.')
    return None if s in ('', 'n/a', '-') else float(s)


def plain(s):
    s = unicodedata.normalize('NFD', s.lower())
    s = ''.join(c for c in s if unicodedata.category(c) != 'Mn')
    return re.sub(r'[^a-z0-9%&]+', ' ', s).strip()


def energy_ok(kcal, p, c, f):
    calc = 4 * p + 4 * c + 9 * f
    return abs(calc - kcal) <= max(15, kcal * .15), calc


def rows(chain):
    out, dropped = [], []
    for line in (SRC / chain['file']).read_text().splitlines():
        if not line.strip() or line.startswith('#'):
            continue
        name, flags, values = [x.strip() for x in line.split('|', 2)]
        hu, en = [x.strip() for x in name.split(' / ', 1)]
        flags = re.findall(r'a=[^|]*$|\S+', flags) if 'a=' not in flags else flags.split(' a=')[0].split() + ['a=' + flags.split(' a=')[1]]
        if chain['kind'] == 'kfc':
            v = values.split()
            g, kcal, f, c = num(v[0]), num(v[2]), num(v[4]), num(v[8])
            cands = [num(v[13])] + ([num(v[12])] if num(v[12]) is not None else [])
            p = min((x for x in cands if x is not None), key=lambda x: abs(4 * x + 4 * c + 9 * f - kcal))   # a missing % column shifts protein left
        else:
            g, kcal, f, sat, c, sugar, p = [num(x) for x in values.split('|')]
        ok, calc = energy_ok(kcal, p, c, f)
        if not ok or g is None or g <= 0:
            dropped.append(f"{chain['name']}: {hu} ({kcal} kcal printed, {calc:.0f} from macros)")
            continue
        aliases, opts = [], {}
        if 'u' in flags:
            aliases += [plain(hu), plain(en)]
        for x in flags:                                   # a=short;names that answer without the chain's name
            if x.startswith('a='):
                aliases += [plain(n) if not n.startswith(tuple(chain['short'])) else n for n in x[2:].split(';')]
        for s in chain['short']:
            aliases += [s + ' ' + plain(hu), s + ' ' + plain(en)]
        crust = next((x.split(':')[1] for x in flags if x.startswith('pizza:')), None)
        if crust:
            base = plain(hu.split(' pizza,')[0])
            aliases += ['pizza hut ' + a.format(n=base) for a in CRUST_ALIASES[crust]]
            opts['slices'] = 8
        if 'pcs' in flags:
            opts['piece'] = 1
        if 'ml' in flags:
            opts['ml'] = 1
        aliases = list(dict.fromkeys(a for a in aliases if a))
        out.append([hu, en, g, kcal, round(p, 2), round(c, 2), round(f, 2), '|'.join(aliases), opts])
    return out, dropped


def main():
    menus, dropped = [], []
    for chain in CHAINS:
        r, d = rows(chain)
        dropped += d
        menus.append({k: chain[k] for k in ('name', 'short', 'ref', 'refEn')} | {'rows': r})
    body = json.dumps(menus, ensure_ascii=False, separators=(',', ':'))
    head = ('/* Generated by tools/build_chain_menus.py from tools/chain-data/*.txt (official Hungarian nutrition tables).\n'
            '   Rows: [name, English name, portion g/ml, kcal, protein, carbs, fat, extra names, options]. Do not edit by hand. */\n')
    (ROOT / 'data' / 'chain-menus.js').write_text(head + 'window.CHAIN_MENUS=' + body + ';\n', encoding='utf-8')
    print('rows:', {m['name']: len(m['rows']) for m in menus})
    print('left out (energy does not match the printed macros):' if dropped else 'no rows left out')
    for d in dropped:
        print('  ' + d)


if __name__ == '__main__':
    sys.exit(main())
