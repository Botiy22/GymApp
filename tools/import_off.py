#!/usr/bin/env python3
"""Import store products from an Open Food Facts CSV export into data/store-products.js.

Usage:  python3 tools/import_off.py path/to/export.csv [more.csv ...]

Accepts the tab-separated OFF export (the full products CSV or a search-results download). Keeps products sold in
Hungary whose store or brand belongs to Lidl, Aldi, Tesco, SPAR or Auchan, with complete values per 100 g that pass an
energy check (4/4/9 kcal within 20 %). Data: Open Food Facts contributors, ODbL — credited in the app with each item.
The app still prefers a label the user saved; these values replace the generic ≈ estimate.
"""
import csv, json, os, pathlib, re, sys, unicodedata
from datetime import date

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = pathlib.Path(os.environ.get('STORE_PRODUCTS_OUT') or ROOT / 'data' / 'store-products.js')
STORES = {'lidl': 'Lidl', 'aldi': 'Aldi', 'tesco': 'Tesco', 'spar': 'SPAR', 'interspar': 'SPAR', 'auchan': 'Auchan'}
OWN = {'pilos': 'Lidl', 'milbona': 'Lidl', 'crownfield': 'Lidl', 'alesto': 'Lidl', 'freshona': 'Lidl', 'combino': 'Lidl', 'solevita': 'Lidl',
       'chef select': 'Lidl', 'dulano': 'Lidl', 'fin carre': 'Lidl', 'milsani': 'Aldi', 'moser roth': 'Aldi', 'choceur': 'Aldi',
       'golden bridge': 'Aldi', 'tesco': 'Tesco', 'tesco finest': 'Tesco', 'spar': 'SPAR', 's budget': 'SPAR', 'despar': 'SPAR', 'auchan': 'Auchan'}
csv.field_size_limit(10 ** 8)


def plain(s):
    s = unicodedata.normalize('NFD', str(s or '').lower())
    return re.sub(r'[^a-z0-9%]+', ' ', ''.join(c for c in s if unicodedata.category(c) != 'Mn')).strip()


def num(v):
    try:
        x = float(str(v).replace(',', '.'))
        return x if x == x and x >= 0 else None
    except ValueError:
        return None


def store_of(row):
    stores = plain(row.get('stores', '')) + ' ' + plain(row.get('stores_tags', ''))
    brands = plain(row.get('brands', ''))
    for k, v in STORES.items():
        if re.search(r'\b' + k + r'\b', stores):
            return v
    for k, v in sorted(OWN.items(), key=lambda kv: -len(kv[0])):
        if re.search(r'\b' + k + r'\b', brands):
            return v
    return None


def read(path):
    with open(path, newline='', encoding='utf-8', errors='replace') as fh:
        sample = fh.read(4096); fh.seek(0)
        dialect = csv.excel_tab if sample.count('\t') > sample.count(',') else csv.excel
        yield from csv.DictReader(fh, dialect=dialect)


def main(paths):
    rows, seen, skipped = {}, set(), 0
    for path in paths:
        for r in read(path):
            countries = plain(r.get('countries_en', '') or r.get('countries', '') or r.get('countries_tags', ''))
            if 'hungary' not in countries and 'magyarorszag' not in countries:
                continue
            store = store_of(r)
            name = (r.get('product_name_hu') or r.get('product_name') or '').strip()
            brand = (r.get('brands') or '').split(',')[0].strip()
            kcal = num(r.get('energy-kcal_100g')) or (num(r.get('energy_100g')) or 0) / 4.184 or None
            p, c, f = num(r.get('proteins_100g')), num(r.get('carbohydrates_100g')), num(r.get('fat_100g'))
            if not store or not name or not brand or None in (kcal, p, c, f) or p + c + f > 105 or kcal > 950:
                skipped += 1; continue
            if abs(4 * p + 4 * c + 9 * f - kcal) > max(20, kcal * .2):
                skipped += 1; continue
            key = (plain(brand), plain(name))
            if key in seen:
                continue
            seen.add(key)
            serving = num(r.get('serving_quantity'))
            row = [name[:80], brand[:40], store, round(kcal, 1), round(p, 1), round(c, 1), round(f, 1), round(serving, 1) if serving and 5 <= serving <= 1000 else 0, (r.get('code') or '')[:14]]
            rows.setdefault(brand, []).append(row)
    brands = [{'name': b, 'rows': rs} for b, rs in sorted(rows.items(), key=lambda kv: -len(kv[1]))]
    data = {'source': 'Open Food Facts (ODbL)', 'imported': date.today().isoformat(), 'count': sum(len(b['rows']) for b in brands), 'brands': brands}
    OUT.write_text('/* Generated by tools/import_off.py from an Open Food Facts export (ODbL; © Open Food Facts contributors).\n'
                   '   Rows: [name, brand, store, kcal, protein, carbs, fat per 100 g, serving g (0 = none), barcode]. */\n'
                   'window.STORE_PRODUCTS=' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
    print(f"{data['count']} products from {len(brands)} brands written; {skipped} skipped (no store/values or failed the energy check)")


if __name__ == '__main__':
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    main(sys.argv[1:])
