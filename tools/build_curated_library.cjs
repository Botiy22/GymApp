/* Rebuild the active library without modifying the archived dataset. */
const fs=require('node:fs');global.window=global;
for(const f of ['data/exercises','data/exercises.hu','data/recipes','data/figures','data/additions','data/routine-art','data/library-expansion','data/exercise-guides','data/exercise-guides-extra','data/generated-exercise-art'])require('../'+f+'.js');
const curated=Object.entries(EXERCISE_GUIDES).map(([id,g])=>{
 const legacy=EXERCISES.find(e=>e.id===id),art=GENERATED_EXERCISE_ART[id];
 if(!legacy||!art||art.source!=='generated')throw Error('Incomplete exercise '+id);
 for(const path of [...art.pair,art.thumb])if(!fs.existsSync(path))throw Error('Missing '+path);
 return {...legacy,n:g.en||legacy.n,i:g.steps.en,hu:g.hu,curated:true,k:0};
});
if(curated.length!==100)throw Error('Expected 100 unique exercises');
fs.writeFileSync('data/exercises-curated.js','/* Generated by tools/build_curated_library.cjs. Stable IDs preserve plans and logs. */\nwindow.CURATED_EXERCISES = '+JSON.stringify(curated,null,2)+';\n');
console.log('Curated exercises:',curated.length);
