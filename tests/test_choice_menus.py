        self.assertEqual(p.locator('select[name=type]').input_value(),'swim')
        p.locator('input[name=minutes]').fill('40');p.locator('input[name=weight]').fill('80')
        choose(p,'select[name=pool]','50');p.locator('input[name=laps_free]').fill('20')
        choose(p,'select[name=intensity]','moderate');self.bounds(p,'swim form')
        p.locator('[data-f=cardio] button.primary').click()
        self.assertEqual(p.evaluate('Store.d.workouts.at(-1).cardio[0].pool'),50)
        self.assertEqual(p.locator('.swim-page [data-a=wk-open]').count(),1)
        p.evaluate('document.getAnimations().forEach(a=>a.finish())');p.screenshot(path='/tmp/reppsy-choice-swim.png')
        p.reload();p.wait_for_function('()=>!!window.__gym');select_workout(p,'swim')
        self.assertEqual(p.locator('.swim-page [data-a=wk-open]').count(),1)
        self.assertEqual(errors,[])
