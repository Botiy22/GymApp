    def test_keyboard_disabled_options_native_form_validation_and_dynamic_state(self):
        p,errors=self.page()
        p.evaluate('''()=>{const f=document.createElement('form');f.id='choice-test';f.innerHTML='<label class="fld"><span>Test option</span><select name="sample" required><option value="">Choose</option><option value="a" disabled>Disabled</option><option value="b">Beta</option><option value="c">Charlie</option></select></label><button type="submit">Save</button>';document.querySelector('#view').append(f);f.onsubmit=e=>{e.preventDefault();window.choiceSaved=Object.fromEntries(new FormData(f))};}''')
        summary=p.locator('#choice-test summary');summary.wait_for()
        p.locator('#choice-test [type=submit]').click();self.assertTrue(p.locator('#choice-test details').evaluate('(e)=>e.open'))
        summary.focus();p.keyboard.press('ArrowDown');p.keyboard.press('ArrowDown');p.keyboard.press('Enter')
        self.assertEqual(p.locator('#choice-test select').input_value(),'b')
        self.assertEqual(summary.inner_text(),'Beta');self.assertTrue(summary.evaluate('(e)=>e===document.activeElement'))
        p.locator('#choice-test [type=submit]').click();self.assertEqual(p.evaluate('choiceSaved.sample'),'b')
        summary.click();p.keyboard.press('End');p.keyboard.press('Enter');self.assertEqual(summary.inner_text(),'Charlie')
        summary.click();p.keyboard.press('Escape');self.assertFalse(p.locator('#choice-test details').evaluate('(e)=>e.open'))
        p.evaluate("document.querySelector('#choice-test select').add(new Option('Delta','d'))")
        choose(p,'#choice-test select','d');self.assertEqual(summary.inner_text(),'Delta')
        self.assertEqual(errors,[])
